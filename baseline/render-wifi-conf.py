#!/usr/bin/env python3
"""render-wifi-conf.py: print a wpa_supplicant config for the lab hotspot(s).

Usage: render-wifi-conf.py SSID PASSWORD [SSID2 PASSWORD2 ...]
The first pair gets the highest priority. Used by trackc-wifi@<iface>.service,
which udev starts for whatever Wi-Fi interface the laptop has (wlo1, wlp3s0, ...).
Netplan is not used for Wi-Fi: its networkd backend needs the exact interface
name ("match:" is rejected for wifis), and the name differs per laptop.
"""
import sys

args = sys.argv[1:]
if not args or len(args) % 2:
    sys.exit("usage: render-wifi-conf.py SSID PASSWORD [SSID2 PASSWORD2 ...]")
out = ["# Generated by baseline/render-wifi-conf.py (lab remote access only).",
       "ctrl_interface=DIR=/run/wpa_supplicant GROUP=netdev",
       "update_config=0", ""]
pairs = list(zip(args[::2], args[1::2]))
for i, (ssid, pw) in enumerate(pairs):
    if not 8 <= len(pw) <= 63 or '"' in pw or "\n" in pw or not pw.isascii():
        sys.exit(f"password for {ssid!r}: need 8-63 ASCII chars without '\"'")
    out += ["network={",
            f"  ssid={ssid.encode().hex()}",      # hex: any SSID, no quoting issues
            f'  psk="{pw}"',
            "  key_mgmt=WPA-PSK WPA-PSK-SHA256 SAE",  # WPA2, WPA2/3 mixed, WPA3
            "  ieee80211w=1",                         # PMF optional (required by SAE)
            f"  priority={len(pairs) - i}",
            "}", ""]
print("\n".join(out), end="")
